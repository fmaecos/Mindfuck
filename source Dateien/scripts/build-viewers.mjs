import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const read = (p) => readFileSync(resolve(root, p), 'utf8');

const desktop = read('viewer-src/desktop.html')
  .replace('/*NOVNC*/', () => read('viewer-src/vendor/novnc.min.js'))
  .replace('/*APP*/', () => read('viewer-src/desktop.js'));

const terminal = read('viewer-src/terminal.html')
  .replace('/*XTERM_JS*/', () => read('viewer-src/vendor/xterm.min.js'))
  .replace('/*APP*/', () => read('viewer-src/terminal.js'));

const xtermCss = read('viewer-src/vendor/xterm.css');

const out = `// GENERATED by scripts/build-viewers.mjs — do not edit by hand.
// noVNC 1.4.0 (MPL-2.0) and @xterm/xterm 6.0.0 (MIT) are bundled locally so
// the viewer works offline and on devices without a CDN.

export const DESKTOP_HTML: string = ${JSON.stringify(desktop)};

export const TERMINAL_HTML: string = ${JSON.stringify(terminal)};

export const XTERM_CSS: string = ${JSON.stringify(xtermCss)};
`;

mkdirSync(resolve(root, 'lib/generated'), { recursive: true });
writeFileSync(resolve(root, 'lib/generated/viewers.ts'), out);
console.log('viewers.ts written:', (out.length / 1024).toFixed(1), 'KB');
